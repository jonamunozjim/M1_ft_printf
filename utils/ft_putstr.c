#include "../includes/ft_printf.h"

int	ft_putstr(char *s)
{
	unsigned int	i;

	i = 0;
	while (s[i])
	{
		if (write (1, &s[i], 1) < 0)
			return (-1);
		else
			i++;
	}
	return (i);
}
